"""Rolling-origin backtest with purge and embargo.

Fold k tests on days (t0, t0 + test_days]. Training rows are limited to days
<= t0 - purge - embargo, where purge = horizon (a training label looks `horizon` days ahead and
must not reach the test window) and embargo adds a safety gap. Within the training period the last
`cal_days` (separated from the fit part by another `purge`) calibrate the isotonic map.
"""

from __future__ import annotations

import platform
import time
from dataclasses import dataclass
from datetime import date, timedelta

import numpy as np
import pandas as pd
import sklearn
from numpy.typing import NDArray

from pricewatch.model import brier, expected_calibration_error, fit, reliability

FloatArray = NDArray[np.float64]


@dataclass(frozen=True)
class FoldPlan:
    index: int
    train_end: date
    cal_start: date  # first calibration day (fit part ends `purge` days earlier)
    test_start: date
    test_end: date


@dataclass(frozen=True)
class Scores:
    brier: float
    log_loss: float
    ece: float


@dataclass(frozen=True)
class FoldResult:
    plan: FoldPlan
    rows_train: int
    rows_cal: int
    rows_test: int
    model: Scores
    base_rate: Scores
    category_rate: Scores


def log_loss(y: FloatArray, p: FloatArray) -> float:
    q = np.clip(p, 1e-6, 1 - 1e-6)
    return float(-np.mean(y * np.log(q) + (1 - y) * np.log(1 - q)))


def score(y: FloatArray, p: FloatArray) -> Scores:
    return Scores(brier(y, p), log_loss(y, p), expected_calibration_error(reliability(y, p)))


def plan_folds(
    last_label_day: date,
    first_day: date,
    folds: int = 6,
    test_days: int = 45,
    purge: int = 14,
    embargo: int = 7,
    cal_days: int = 90,
    min_train_days: int = 240,
) -> list[FoldPlan]:
    """Folds step backwards from the last day whose label is observed; oldest first."""
    plans: list[FoldPlan] = []
    for k in range(folds):
        test_end = last_label_day - timedelta(days=test_days * (folds - 1 - k))
        t0 = test_end - timedelta(days=test_days)
        train_end = t0 - timedelta(days=purge + embargo)
        if (train_end - first_day).days < min_train_days:
            raise ValueError(f"fold {k}: only {(train_end - first_day).days} training days")
        plans.append(
            FoldPlan(
                k,
                train_end,
                train_end - timedelta(days=cal_days),
                t0 + timedelta(days=1),
                test_end,
            )
        )
    return plans


def _days(frame: pd.DataFrame) -> pd.Series:
    return pd.to_datetime(frame["day"]).dt.date


def run_backtest(
    labelled: pd.DataFrame,
    seed: int,
    horizon: int = 14,
    embargo: int = 7,
    folds: int = 6,
    test_days: int = 45,
    cal_days: int = 90,
) -> list[FoldResult]:
    days = _days(labelled)
    plans = plan_folds(
        days.max(), days.min(), folds, test_days, purge=horizon, embargo=embargo, cal_days=cal_days
    )
    results: list[FoldResult] = []
    for plan in plans:
        d = _days(labelled)
        fit_part = labelled[d <= plan.cal_start - timedelta(days=horizon)]
        cal = labelled[(d >= plan.cal_start) & (d <= plan.train_end)]
        test = labelled[(d >= plan.test_start) & (d <= plan.test_end)]
        model = fit(fit_part, cal, seed)
        y = test["label"].to_numpy(dtype=np.float64)
        train_all = labelled[d <= plan.train_end]
        base = float(train_all["label"].mean())
        by_cat = train_all.groupby("category_code")["label"].mean()
        cat_p = test["category_code"].map(by_cat).fillna(base).to_numpy(dtype=np.float64)
        results.append(
            FoldResult(
                plan,
                len(fit_part),
                len(cal),
                len(test),
                score(y, model.predict_proba(test)),
                score(y, np.full_like(y, base)),
                score(y, cat_p),
            )
        )
    return results


def render_markdown(
    results: list[FoldResult], seed: int, horizon: int, embargo: int, elapsed: float
) -> str:
    """BENCHMARKS.md body generated from a real run (no hand-entered numbers)."""
    head = (
        "# Benchmarks (SIMULATED data)\n\n"
        "Generated by `pricewatch backtest`; every number below comes from that run. "
        "All data is simulated, so these scores say nothing about real prices.\n\n"
        f"- seed: {seed}; horizon: {horizon}d; purge: {horizon}d; embargo: {embargo}d\n"
        f"- python {platform.python_version()}, scikit-learn {sklearn.__version__}, "
        f"numpy {np.__version__}, pandas {pd.__version__}\n"
        f"- elapsed: {elapsed:.1f}s; folds: {len(results)} (rolling origin, expanding train)\n"
        "- baselines: `base` = training-set base rate; `cat` = per-category training rate\n\n"
        "| fold | test window | train/cal/test rows | Brier model / base / cat |"
        " log loss model / base / cat | ECE model / base / cat |\n"
        "|---|---|---|---|---|---|\n"
    )
    rows = []
    for r in results:
        m, b, c = r.model, r.base_rate, r.category_rate
        rows.append(
            f"| {r.plan.index} | {r.plan.test_start} to {r.plan.test_end} "
            f"| {r.rows_train}/{r.rows_cal}/{r.rows_test} "
            f"| {m.brier:.4f} / {b.brier:.4f} / {c.brier:.4f} "
            f"| {m.log_loss:.4f} / {b.log_loss:.4f} / {c.log_loss:.4f} "
            f"| {m.ece:.4f} / {b.ece:.4f} / {c.ece:.4f} |"
        )
    wins = sum(r.model.brier < r.base_rate.brier for r in results)
    foot = (
        f"\n**Mean Brier**: model {float(np.mean([r.model.brier for r in results])):.4f}, "
        f"base {float(np.mean([r.base_rate.brier for r in results])):.4f}, "
        f"cat {float(np.mean([r.category_rate.brier for r in results])):.4f}. "
        f"Model beats the base-rate Brier in {wins}/{len(results)} folds.\n"
    )
    return head + "\n".join(rows) + "\n" + foot


def timed_backtest(
    labelled: pd.DataFrame, seed: int, horizon: int, embargo: int
) -> tuple[list[FoldResult], float]:
    t = time.perf_counter()
    res = run_backtest(labelled, seed, horizon, embargo)
    return res, time.perf_counter() - t
