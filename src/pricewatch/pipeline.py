"""End-to-end run: simulate, featurise, train, calibrate, export static JSON."""

from __future__ import annotations

import json
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from pricewatch.clock import advance_clock, read_clock
from pricewatch.config import load_categories
from pricewatch.features import build_features
from pricewatch.model import (
    brier,
    expected_calibration_error,
    fit,
    reliability,
    split_by_time,
)
from pricewatch.sales import load_calendar
from pricewatch.settings import Settings
from pricewatch.simulator import simulate_all

DISCLAIMER = (
    "SIMULATED DATA: fictional products and prices generated by a seeded simulator. "
    "Not real market data; probabilities are not financial advice."
)


def _write(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = {"simulated": True, "disclaimer": DISCLAIMER, **payload}
    path.write_text(json.dumps(body, indent=1, sort_keys=True), encoding="utf-8")


def run(settings: Settings, out_dir: Path, advance: bool = True) -> date:
    """Run one simulated day and write JSON under out_dir. Returns the simulated 'today'."""
    clock_path = settings.data_dir / "clock.json"
    today = advance_clock(clock_path, settings) if advance else read_clock(clock_path, settings)
    cats = load_categories(settings.config_dir)
    events = load_calendar(settings.calendar_path)
    products, prices = simulate_all(cats, settings.seed, settings.start_date, events)
    prices = prices[prices["day"] <= today]
    feats = build_features(prices, products, cats, events, settings.horizon_days)
    labelled = feats.dropna(subset=["label"])
    train, cal, test = split_by_time(labelled, today, settings.horizon_days)
    model = fit(train, cal, settings.seed)

    y = test["label"].to_numpy(dtype=np.float64)
    p_test = model.predict_proba(test)
    rel = reliability(y, p_test)
    metrics = {
        "as_of": today.isoformat(),
        "horizon_days": settings.horizon_days,
        "brier": brier(y, p_test),
        "base_rate_brier": brier(y, np.full_like(y, y.mean())),
        "ece": expected_calibration_error(rel),
        "test_rows": len(test),
        "reliability": rel,
        "assumptions": "Simulator parameters are documented assumptions, not real calibration.",
    }
    _write(out_dir / "metrics.json", metrics)

    latest = feats[pd.to_datetime(feats["day"]).dt.date == today].copy()
    latest["probability"] = model.predict_proba(latest)
    prob = dict(zip(latest["sku"], latest["probability"], strict=True))
    last_price = dict(zip(latest["sku"], latest["price"], strict=True))
    items: list[dict[str, Any]] = []
    for prod in products:
        if prod.sku not in prob:
            continue
        hist = prices[(prices["sku"] == prod.sku) & (prices["day"] > today - timedelta(days=120))]
        item = {
            "sku": prod.sku,
            "category": prod.category,
            "brand": prod.brand,
            "name": prod.name,
            "as_of": today.isoformat(),
            "price": round(float(last_price[prod.sku]), 2),
            "probability": round(float(prob[prod.sku]), 4),
            "history": [
                {"day": d.isoformat(), "price": float(v)}
                for d, v in zip(hist["day"], hist["price"], strict=True)
            ],
        }
        items.append(item)
        _write(out_dir / "items" / f"{prod.sku}.json", item)
    _write(
        out_dir / "index.json",
        {
            "as_of": today.isoformat(),
            "horizon_days": settings.horizon_days,
            "categories": [{"id": c.id, "name": c.name} for c in cats],
            "items": [{k: v for k, v in i.items() if k != "history"} for i in items],
        },
    )
    return today
